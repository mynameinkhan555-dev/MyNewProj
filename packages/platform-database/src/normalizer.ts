/**
 * Catalog Normalizer
 * Normalizes PostgreSQL schema catalog for fingerprint generation according to BASELINE-CONTRACT.md
 */

import { Catalog, Table, Column, Constraint, Index, Enum, Sequence, NormalizedConstraint, NormalizedTable } from './introspection.js';

export class CatalogNormalizer {
  normalize(catalog: Catalog): any {
    return {
      tables: catalog.tables.map(table => this.normalizeTable(table)),
      enums: catalog.enums.map(enum_ => this.normalizeEnum(enum_)),
      sequences: catalog.sequences.map(seq => this.normalizeSequence(seq)),
    };
  }

  private normalizeTable(table: Table): any {
    return {
      ...table,
      columns: table.columns.map(col => this.normalizeColumn(col)),
      constraints: table.constraints
        .filter(constraint => this.shouldKeepConstraint(constraint))
        .map(constraint => this.normalizeConstraint(constraint)),
      indexes: table.indexes.map(idx => this.normalizeIndex(idx)),
    };
  }

  private normalizeColumn(column: Column): Column {
    // Normalize default values according to contract
    let defaultValue = column.defaultValue;
    if (defaultValue) {
      // Remove PostgreSQL type casts: 'value'::type -> value
      defaultValue = defaultValue.replace(/^'(.+)'::[^,]+$/, '$1');
      // Remove quotes from simple values: 'value' -> value
      defaultValue = defaultValue.replace(/^'(.+)'$/, '$1');
      // Trim whitespace
      defaultValue = defaultValue.trim();
    }

    // Normalize generated expression
    let generatedExpression = column.generatedExpression;
    if (generatedExpression) {
      generatedExpression = generatedExpression.trim();
    }

    return {
      ...column,
      defaultValue,
      generatedExpression,
    };
  }

  private shouldKeepConstraint(constraint: Constraint): boolean {
    // PostgreSQL auto-generated constraint names matching pattern:
    // \d+_\d+_\d+_(not_null|check)$
    // These are normalized to null (removed)
    // However, user-defined CHECK constraints are kept
    const autoGeneratedPattern = /^\d+_\d+_\d+_(not_null|check)$/;
    const isAutoGenerated = autoGeneratedPattern.test(constraint.name || '');

    // If it's CHECK and not auto-generated, keep it
    if (constraint.type === 'CHECK' && !isAutoGenerated) {
      return true;
    }

    // Otherwise, filter out auto-generated
    return !isAutoGenerated;
  }

  private normalizeConstraint(constraint: Constraint): any {
    // If constraint name is auto-generated, set to null
    const autoGeneratedPattern = /^\d+_\d+_\d+_(not_null|check)$/;
    const isAutoGenerated = autoGeneratedPattern.test(constraint.name || '');

    // For CHECK constraints that are not auto-generated, keep the name
    // For auto-generated constraints, set name to null
    let name: string | null;
    if (constraint.type === 'CHECK' && !isAutoGenerated) {
      name = constraint.name;
    } else if (isAutoGenerated) {
      name = null;
    } else {
      name = constraint.name;
    }

    // Deduplicate reference columns
    let references;
    if (constraint.references) {
      references = {
        ...constraint.references,
        columns: [...new Set(constraint.references.columns)].sort(),
      };
    }

    return {
      ...constraint,
      name,
      references,
    };
  }

  private normalizeIndex(index: Index): Index {
    // Deduplicate columns and expressions
    const columns = [...new Set(index.columns)].sort();
    const expressions = [...new Set(index.expressions)].sort();

    return {
      ...index,
      columns,
      expressions,
    };
  }

  private normalizeEnum(enum_: Enum): Enum {
    // Enum values are already sorted by database query
    return {
      ...enum_,
      values: [...enum_.values].sort(),
    };
  }

  private normalizeSequence(seq: Sequence): Sequence {
    return {
      ...seq,
    };
  }
}
